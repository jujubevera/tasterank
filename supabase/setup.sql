-- TasteRank database setup
-- Fresh install: paste this whole file into Supabase → SQL Editor → New query and press Run, then do the same with
-- migrate-002-flavours.sql and migrate-003-no-names.sql, in that order. Together they give the same database as the live project.
-- (This file creates the original foods tables; migration 002 adds products and flavours and copies the foods across.)
--
-- What it creates:
--   profiles     one row per signed-in person (name from Google, home country)
--   items        foods; 'pending' until 5 people approve, then 'live'
--   ratings      one emoji rating (1-5) per person per food
--   votes        one approval vote per person per pending food
--   suggestions  category ideas people send in (read them in Table Editor)
-- Security: everyone can see foods and totals; people can only add or change their own
-- ratings, votes and profile. Nobody can see who rated what.

-- ---------- Tables ----------
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  home_country text check (char_length(home_country) <= 60),
  created_at timestamptz not null default now()
);

create table public.items (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  brand text not null default '' check (char_length(brand) <= 60),
  country text not null check (char_length(country) between 1 and 60),
  category text not null check (category in ('Chocolate & sweets','Crisps & snacks','Biscuits','Drinks','Spreads & sauces')),
  emoji text not null default '🍽️' check (char_length(emoji) <= 8),
  image_url text check (image_url is null or (image_url ~ '^https://' and char_length(image_url) <= 500)),
  status text not null default 'pending' check (status in ('pending','live')),
  submitted_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.ratings (
  item_id bigint not null references public.items(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  score smallint not null check (score between 1 and 5),
  updated_at timestamptz not null default now(),
  primary key (item_id, user_id)
);

create table public.votes (
  item_id bigint not null references public.items(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (item_id, user_id)
);

create table public.suggestions (
  id bigint generated by default as identity primary key,
  user_id uuid default auth.uid() references auth.users(id) on delete set null,
  name text not null check (char_length(name) between 1 and 60),
  created_at timestamptz not null default now()
);

-- ---------- Security rules ----------
alter table public.profiles    enable row level security;
alter table public.items       enable row level security;
alter table public.ratings     enable row level security;
alter table public.votes       enable row level security;
alter table public.suggestions enable row level security;

create policy "read own profile"   on public.profiles for select to authenticated using (id = auth.uid());
create policy "update own profile" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

create policy "anyone can read items" on public.items for select to anon, authenticated using (true);
create policy "signed-in people submit pending items" on public.items for insert to authenticated
  with check (submitted_by = auth.uid() and status = 'pending');
-- Hide who submitted each item from the public.
revoke select on public.items from anon, authenticated;
grant select (id, name, brand, country, category, emoji, image_url, status, created_at) on public.items to anon, authenticated;

create policy "read own ratings"  on public.ratings for select to authenticated using (user_id = auth.uid());
create policy "rate live items"   on public.ratings for insert to authenticated
  with check (user_id = auth.uid() and exists (select 1 from public.items i where i.id = item_id and i.status = 'live'));
create policy "change own rating" on public.ratings for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "read own votes"        on public.votes for select to authenticated using (user_id = auth.uid());
create policy "vote on pending items" on public.votes for insert to authenticated
  with check (user_id = auth.uid() and exists (select 1 from public.items i where i.id = item_id and i.status = 'pending'));

create policy "signed-in people suggest" on public.suggestions for insert to authenticated with check (user_id = auth.uid());

-- ---------- Automatic behaviour ----------
-- New sign-in → create their profile with their Google name.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name) values (new.id, new.raw_user_meta_data->>'full_name');
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Submitting a food counts as its first approval vote.
create function public.vote_for_own_item() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.submitted_by is not null then
    insert into public.votes (item_id, user_id) values (new.id, new.submitted_by);
  end if;
  return new;
end $$;
create trigger on_item_submitted after insert on public.items
  for each row execute function public.vote_for_own_item();

-- 5 approval votes → the food goes live. (Keep in sync with APPROVAL_VOTES in index.html.)
create function public.promote_when_approved() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.items set status = 'live'
   where id = new.item_id and status = 'pending'
     and (select count(*) from public.votes v where v.item_id = new.item_id) >= 5;
  return new;
end $$;
create trigger on_vote_cast after insert on public.votes
  for each row execute function public.promote_when_approved();

-- ---------- Functions the website calls ----------
-- All foods with rating totals and vote counts (no personal data).
create function public.item_list()
returns table (id bigint, name text, brand text, country text, category text, emoji text, image_url text, status text,
               r1 int, r2 int, r3 int, r4 int, r5 int, votes int, mine boolean)
language sql stable security definer set search_path = '' as $$
  select i.id, i.name, i.brand, i.country, i.category, i.emoji, i.image_url, i.status,
         count(r.score) filter (where r.score = 1)::int,
         count(r.score) filter (where r.score = 2)::int,
         count(r.score) filter (where r.score = 3)::int,
         count(r.score) filter (where r.score = 4)::int,
         count(r.score) filter (where r.score = 5)::int,
         (select count(*) from public.votes v where v.item_id = i.id)::int,
         coalesce(i.submitted_by = auth.uid(), false)
  from public.items i
  left join public.ratings r on r.item_id = i.id
  group by i.id
  order by i.id;
$$;
grant execute on function public.item_list() to anon, authenticated;

-- "Delete my account" button: removes the person and all their ratings, votes and profile.
create function public.delete_me() returns void
language sql security definer set search_path = '' as $$
  delete from auth.users where id = auth.uid();
$$;
revoke execute on function public.delete_me() from public, anon;
grant execute on function public.delete_me() to authenticated;

